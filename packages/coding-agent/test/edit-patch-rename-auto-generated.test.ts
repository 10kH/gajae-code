import { afterEach, beforeEach, expect, it } from "bun:test";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { resetSettingsForTest, Settings } from "@gajae-code/coding-agent/config/settings";
import { EditTool } from "@gajae-code/coding-agent/edit";
import type { ToolSession } from "@gajae-code/coding-agent/tools";

function makeSession(cwd: string, blockAutoGenerated: boolean): ToolSession {
	return {
		cwd,
		hasUI: false,
		getSessionFile: () => null,
		getSessionSpawns: () => "*",
		enableLsp: false,
		settings: Settings.isolated({
			"edit.mode": "patch",
			"edit.blockAutoGenerated": blockAutoGenerated,
		}),
		getArtifactsDir: () => null,
		getSessionId: () => null,
		getPlanModeState: () => undefined,
	} as unknown as ToolSession;
}

const SOURCE = "line\n";
const MOVED = "moved\n";
const DIFF = "@@\n-line\n+moved";

let tempDir: string;

beforeEach(async () => {
	resetSettingsForTest();
	tempDir = await fs.promises.mkdtemp(path.join(os.tmpdir(), "edit-patch-rename-autogen-"));
	await Settings.init({ inMemory: true, cwd: tempDir, overrides: { "edit.blockAutoGenerated": true } });
});

afterEach(async () => {
	resetSettingsForTest();
	await fs.promises.rm(tempDir, { recursive: true, force: true });
});

async function writePair(sourceName: string, destName: string, destBody: string): Promise<void> {
	await Bun.write(path.join(tempDir, sourceName), SOURCE);
	await Bun.write(path.join(tempDir, destName), destBody);
}

function patchRename(blockAutoGenerated: boolean, sourceName: string, destName: string) {
	const tool = new EditTool(makeSession(tempDir, blockAutoGenerated), "patch");
	return tool.execute("patch-rename-autogen", {
		path: sourceName,
		edits: [{ op: "update", rename: destName, diff: DIFF }],
	});
}

it("refuses to rename a patch onto an existing auto-generated file", async () => {
	const destBody = "package widget\n";
	await writePair("product.ts", "widget.pb.go", destBody);

	await expect(patchRename(true, "product.ts", "widget.pb.go")).rejects.toThrow(/Cannot modify auto-generated file/);

	expect(await Bun.file(path.join(tempDir, "product.ts")).text()).toBe(SOURCE);
	expect(await Bun.file(path.join(tempDir, "widget.pb.go")).text()).toBe(destBody);
});

it("refuses to rename a patch onto a file with an auto-generated header", async () => {
	const destBody = "// Code generated by sqlc. DO NOT EDIT.\nexport const foo = 1;\n";
	await writePair("product.ts", "queries.ts", destBody);

	await expect(patchRename(true, "product.ts", "queries.ts")).rejects.toThrow(/Cannot modify auto-generated file/);

	expect(await Bun.file(path.join(tempDir, "product.ts")).text()).toBe(SOURCE);
	expect(await Bun.file(path.join(tempDir, "queries.ts")).text()).toBe(destBody);
});

it("still allows a patch rename onto an existing handwritten file", async () => {
	await writePair("product.ts", "notes.ts", "keep\n");

	const result = await patchRename(true, "product.ts", "notes.ts");

	expect(result.isError).toBeUndefined();
	expect(await Bun.file(path.join(tempDir, "notes.ts")).text()).toBe(MOVED);
	expect(await Bun.file(path.join(tempDir, "product.ts")).exists()).toBe(false);
});

it("refuses to rename a patch onto a missing auto-generated filename", async () => {
	await Bun.write(path.join(tempDir, "product.ts"), SOURCE);

	await expect(patchRename(true, "product.ts", "fresh.generated.ts")).rejects.toThrow(
		/Cannot modify auto-generated file/,
	);

	expect(await Bun.file(path.join(tempDir, "product.ts")).text()).toBe(SOURCE);
	expect(await Bun.file(path.join(tempDir, "fresh.generated.ts")).exists()).toBe(false);
});

it("still allows a patch rename onto a new handwritten path", async () => {
	await Bun.write(path.join(tempDir, "product.ts"), SOURCE);

	const result = await patchRename(true, "product.ts", "out.ts");

	expect(result.isError).toBeUndefined();
	expect(await Bun.file(path.join(tempDir, "out.ts")).text()).toBe(MOVED);
	expect(await Bun.file(path.join(tempDir, "product.ts")).exists()).toBe(false);
});

it("still allows a patch rename onto an auto-generated file when the setting is off", async () => {
	await writePair("product.ts", "widget.pb.go", "package widget\n");

	const result = await patchRename(false, "product.ts", "widget.pb.go");

	expect(result.isError).toBeUndefined();
	expect(await Bun.file(path.join(tempDir, "widget.pb.go")).text()).toBe(MOVED);
	expect(await Bun.file(path.join(tempDir, "product.ts")).exists()).toBe(false);
});
