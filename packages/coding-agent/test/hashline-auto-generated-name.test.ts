import { afterEach, beforeEach, expect, it } from "bun:test";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { resetSettingsForTest, Settings } from "@gajae-code/coding-agent/config/settings";
import { computeLineHash, EditTool } from "@gajae-code/coding-agent/edit";
import type { ToolSession } from "@gajae-code/coding-agent/tools";

function makeSession(cwd: string, blockAutoGenerated: boolean): ToolSession {
	return {
		cwd,
		hasUI: false,
		getSessionFile: () => null,
		getSessionSpawns: () => "*",
		enableLsp: false,
		settings: Settings.isolated({
			"edit.mode": "hashline",
			"edit.blockAutoGenerated": blockAutoGenerated,
		}),
		getArtifactsDir: () => null,
		getSessionId: () => null,
		getPlanModeState: () => undefined,
	} as unknown as ToolSession;
}

function hashlineReplace(file: string, current: string, next: string): string {
	const anchor = `1${computeLineHash(1, current)}`;
	return `§${file}\n≔${anchor}..${anchor}\n${next}\n`;
}

let tempDir: string;

beforeEach(async () => {
	resetSettingsForTest();
	tempDir = await fs.promises.mkdtemp(path.join(os.tmpdir(), "hashline-autogen-"));
	await Settings.init({ inMemory: true, cwd: tempDir, overrides: { "edit.blockAutoGenerated": true } });
});

afterEach(async () => {
	resetSettingsForTest();
	await fs.promises.rm(tempDir, { recursive: true, force: true });
});

async function writeFixture(name: string, body: string): Promise<string> {
	const filePath = path.join(tempDir, name);
	await fs.promises.mkdir(path.dirname(filePath), { recursive: true });
	await Bun.write(filePath, body);
	return filePath;
}

it("refuses a generated filename with no header marker through hashline edit", async () => {
	const original = "package widget\n";
	const filePath = await writeFixture("widget.gen.ts", original);
	const tool = new EditTool(makeSession(tempDir, true), "hashline");

	await expect(
		tool.execute("hashline-gen-name", {
			input: hashlineReplace("widget.gen.ts", "package widget", "package tampered"),
		}),
	).rejects.toThrow(/Cannot modify auto-generated file/);

	expect(await Bun.file(filePath).text()).toBe(original);
});

